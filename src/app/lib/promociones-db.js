/**
 * Promociones en la base: leer las vigentes (tienda y cobro), leer todas
 * (panel) y guardar. Solo servidor. Las reglas (descuento, estado, validacion)
 * estan en promociones.js; la ruta es /api/promociones.
 *
 * El precio de oferta no se guarda: se calcula al leer, desde el precio de WEB
 * de ese momento y el descuento de la promocion. Asi la tienda, el carrito y
 * el cobro (create-checkout-session) siempre usan el mismo numero.
 */
import { DeleteObjectCommand, PutObjectCommand } from '@aws-sdk/client-s3';

import { consultar, enTransaccion } from '@/app/lib/refautomex-db';
import { bucketName, claveDeObjeto, s3Client } from '@/app/lib/s3-storage';
import {
    MAX_FOTO_MB,
    TIPOS_DESCUENTO,
    TIPOS_FOTO,
    ahorroPorcentaje,
    precioPromocion,
    validarPromocion,
} from '@/app/lib/promociones';

// El despliegue no corre `db:pg:push`: las tablas se crean al guardar la
// primera promocion y tienen que ser identicas a `promocion` y
// `promocion_producto` en lib/db/schema.pg.js.
const CREAR_TABLAS = [
    `CREATE TABLE IF NOT EXISTS promocion (
        idpromocion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
        titulo varchar(120) NOT NULL,
        descripcion varchar(500),
        foto varchar(300),
        inicio timestamp(3) with time zone NOT NULL,
        fin timestamp(3) with time zone NOT NULL,
        activa boolean DEFAULT true NOT NULL,
        creado_por integer,
        actualizado_por integer,
        creado timestamp(3) DEFAULT now() NOT NULL,
        actualizado timestamp(3) DEFAULT now() NOT NULL,
        CONSTRAINT promocion_creado_por_usuario_idusuario_fk FOREIGN KEY (creado_por)
            REFERENCES usuario (idusuario) ON DELETE SET NULL,
        CONSTRAINT promocion_actualizado_por_usuario_idusuario_fk FOREIGN KEY (actualizado_por)
            REFERENCES usuario (idusuario) ON DELETE SET NULL
    )`,
    'CREATE INDEX IF NOT EXISTS promocion_vigencia_idx ON promocion (inicio, fin)',
    `CREATE TABLE IF NOT EXISTS promocion_producto (
        idpromocion integer NOT NULL,
        num_parte varchar(100) NOT NULL,
        tipo varchar(12) NOT NULL,
        valor numeric(10, 2) NOT NULL,
        CONSTRAINT promocion_producto_pk PRIMARY KEY (idpromocion, num_parte),
        CONSTRAINT promocion_producto_idpromocion_promocion_idpromocion_fk FOREIGN KEY (idpromocion)
            REFERENCES promocion (idpromocion) ON DELETE CASCADE,
        CONSTRAINT promocion_producto_num_parte_producto_num_parte_fk FOREIGN KEY (num_parte)
            REFERENCES producto (num_parte) ON DELETE CASCADE ON UPDATE CASCADE
    )`,
    'CREATE INDEX IF NOT EXISTS promocion_producto_num_parte_idx ON promocion_producto (num_parte)',
];

/** Error con codigo HTTP: la ruta lo devuelve tal cual. */
export class ErrorPromocion extends Error {
    constructor(estado, mensaje, detalle) {
        super(mensaje);
        this.estado = estado;
        this.detalle = detalle;
    }
}

// Sin tabla (nadie ha creado una promocion) no hay promociones.
const sinTabla = (error) => error?.code === '42P01';

// El precio de WEB es el mismo que cobra create-checkout-session: el mayor de
// los renglones de WEB, si hubiera dos.
const PRECIO_WEB = `
    LEFT JOIN LATERAL (
        SELECT max(d.precio) AS precio, max(d.costo) AS costo, max(d.existencia) AS existencia
          FROM detalle d JOIN sucursal s USING (idsucursal)
         WHERE d.num_parte = pp.num_parte AND s.sucursal = 'WEB'
    ) w ON true`;

const leerFilas = async (sql, parametros) => {
    try {
        return await consultar(sql, parametros);
    } catch (error) {
        if (sinTabla(error)) return [];
        throw error;
    }
};

const aIso = (valor) => (valor instanceof Date ? valor.toISOString() : new Date(valor).toISOString());

const productoDeFila = (fila) => {
    const regular = Number(fila.regular) || 0;
    const precio = precioPromocion(regular, fila.tipo, fila.valor);
    return {
        num_parte: fila.num_parte,
        descripcion: fila.producto,
        grupo: fila.grupo || null,
        rutas: Array.isArray(fila.rutas) ? fila.rutas : [],
        existencia: Number(fila.existencia) || 0,
        tipo: fila.tipo,
        valor: Number(fila.valor),
        precioRegular: regular || null,
        precio,
        ahorro: precio === null ? 0 : ahorroPorcentaje(regular, precio),
    };
};

/**
 * Las promociones vigentes en este momento, con sus productos y precios. Un
 * producto que ya no esta activo, ya no esta en WEB o cuyo descuento ya no
 * baja el precio (un precio fijo por encima del de WEB) no sale; una
 * promocion sin productos tampoco. Con `partes` solo esos productos (cobro).
 */
export const leerPromocionesVigentes = async ({ partes } = {}) => {
    const filtro = partes ? 'AND pp.num_parte = ANY(?::text[])' : '';
    const filas = await leerFilas(
        `SELECT pr.idpromocion, pr.titulo, pr.descripcion AS detalle, pr.foto, pr.inicio, pr.fin,
                pp.num_parte, pp.tipo, pp.valor, p.descripcion AS producto,
                CASE WHEN p.idgrupo > 0 THEN g.grupo END AS grupo,
                w.precio AS regular, w.existencia,
                COALESCE((SELECT json_agg(i.ruta ORDER BY i."idImagen") FROM imagenes i WHERE i.num_parte = pp.num_parte), '[]'::json) AS rutas
           FROM promocion pr
           JOIN promocion_producto pp USING (idpromocion)
           JOIN producto p ON p.num_parte = pp.num_parte AND p.status = 'A'
           LEFT JOIN grupo g ON g.idgrupo = p.idgrupo
           ${PRECIO_WEB}
          WHERE pr.activa AND now() >= pr.inicio AND now() < pr.fin AND w.precio > 0 ${filtro}
          ORDER BY pr.fin, pr.idpromocion, p.descripcion`,
        partes ? [partes] : []
    );

    const promociones = new Map();
    filas.forEach((fila) => {
        const producto = productoDeFila(fila);
        if (producto.precio === null) return;
        if (!promociones.has(fila.idpromocion)) {
            promociones.set(fila.idpromocion, {
                idpromocion: fila.idpromocion,
                titulo: fila.titulo,
                descripcion: fila.detalle || '',
                foto: fila.foto || null,
                inicio: aIso(fila.inicio),
                fin: aIso(fila.fin),
                productos: [],
            });
        }
        promociones.get(fila.idpromocion).productos.push(producto);
    });
    return [...promociones.values()];
};

/**
 * Para el cobro: num_parte -> { precio, idpromocion, titulo } con el precio de
 * oferta vigente. Si un producto esta en dos promociones, gana la mas barata.
 */
export const ofertasVigentesDe = async (partes) => {
    const ofertas = new Map();
    if (!partes?.length) return ofertas;
    const promociones = await leerPromocionesVigentes({ partes });
    promociones.forEach((promocion) => {
        promocion.productos.forEach((producto) => {
            const actual = ofertas.get(producto.num_parte);
            if (!actual || producto.precio < actual.precio) {
                ofertas.set(producto.num_parte, {
                    precio: producto.precio,
                    idpromocion: promocion.idpromocion,
                    titulo: promocion.titulo,
                });
            }
        });
    });
    return ofertas;
};

/**
 * Todas las promociones para el panel, de la mas nueva a la mas vieja, con
 * cada producto como esta hoy: su precio de WEB, su costo (para la utilidad)
 * y si sigue en WEB.
 */
export const leerPromocionesPanel = async () => {
    const promociones = await leerFilas(
        `SELECT idpromocion, titulo, descripcion, foto, inicio, fin, activa, creado
           FROM promocion ORDER BY inicio DESC, idpromocion DESC`
    );
    if (!promociones.length) return [];
    const productos = await leerFilas(
        `SELECT pp.idpromocion, pp.num_parte, pp.tipo, pp.valor, p.descripcion AS producto, p.status,
                CASE WHEN p.idgrupo > 0 THEN g.grupo END AS grupo,
                w.precio AS regular, w.costo, w.existencia,
                COALESCE((SELECT json_agg(i.ruta ORDER BY i."idImagen") FROM imagenes i WHERE i.num_parte = pp.num_parte), '[]'::json) AS rutas
           FROM promocion_producto pp
           JOIN producto p ON p.num_parte = pp.num_parte
           LEFT JOIN grupo g ON g.idgrupo = p.idgrupo
           ${PRECIO_WEB}
          ORDER BY p.descripcion`
    );
    const porPromocion = new Map(promociones.map((p) => [p.idpromocion, []]));
    productos.forEach((fila) => {
        porPromocion.get(fila.idpromocion)?.push({
            ...productoDeFila(fila),
            costo: Number(fila.costo) || null,
            enWeb: Number(fila.regular) > 0 && fila.status === 'A',
        });
    });
    return promociones.map((p) => ({
        idpromocion: p.idpromocion,
        titulo: p.titulo,
        descripcion: p.descripcion || '',
        foto: p.foto || null,
        inicio: aIso(p.inicio),
        fin: aIso(p.fin),
        activa: Boolean(p.activa),
        creado: aIso(p.creado),
        productos: porPromocion.get(p.idpromocion) || [],
    }));
};

// --------------------------------------------------------------- escribir --

const limpiarNombre = (nombre = '') =>
    String(nombre).toLowerCase().replace(/\s+/g, '_').replace(/[^a-z0-9._-]/g, '').slice(-80) || 'foto.jpg';

/** Revisa la foto subida: tipo de imagen y tamano. */
export const revisarFoto = (archivo) => {
    if (!archivo || typeof archivo === 'string') return null;
    if (!TIPOS_FOTO.includes(archivo.type)) {
        throw new ErrorPromocion(400, 'La foto debe ser JPG, PNG o WebP.');
    }
    if (archivo.size > MAX_FOTO_MB * 1024 * 1024) {
        throw new ErrorPromocion(400, `La foto pesa mas de ${MAX_FOTO_MB} MB.`);
    }
    return archivo;
};

const subirFoto = async (idpromocion, archivo) => {
    // `key` es lo que se guarda en la base y lo que la tienda pega despues de
    // NEXT_PUBLIC_S3, igual que las fotos de productos.
    const key = `promocion/${idpromocion}/${Date.now()}-${limpiarNombre(archivo.name)}`;
    await s3Client.send(new PutObjectCommand({
        Bucket: bucketName,
        Key: claveDeObjeto(key),
        Body: Buffer.from(await archivo.arrayBuffer()),
        ContentType: archivo.type,
        // La tienda la pide en cada visita: que el navegador la guarde un dia.
        // Una foto nueva lleva otra llave, asi que no se queda la vieja.
        CacheControl: 'public, max-age=86400',
    }));
    return key;
};

export const borrarFoto = async (key) => {
    if (!key) return;
    try {
        await s3Client.send(new DeleteObjectCommand({ Bucket: bucketName, Key: claveDeObjeto(key) }));
    } catch (error) {
        // Una foto que no se pudo borrar solo ocupa espacio: no tumba el guardado.
        console.error('[promociones] No se pudo borrar la foto', key, error.message);
    }
};

// Lo que llega del navegador -> datos limpios. Los productos repetidos se
// quedan con el ultimo.
const normalizarDatos = (datos) => {
    const productos = new Map();
    (Array.isArray(datos?.productos) ? datos.productos : []).forEach((producto) => {
        const parte = String(producto?.num_parte ?? '').trim();
        if (parte) productos.set(parte, { num_parte: parte, tipo: producto.tipo, valor: Number(producto.valor) });
    });
    return {
        titulo: String(datos?.titulo ?? '').trim(),
        descripcion: String(datos?.descripcion ?? '').trim(),
        inicio: datos?.inicio,
        fin: datos?.fin,
        activa: datos?.activa !== false,
        productos: [...productos.values()],
    };
};

/**
 * Crea (sin `idpromocion`) o reemplaza una promocion con sus productos. La
 * foto es obligatoria al crear; al editar, una nueva reemplaza a la anterior
 * y la anterior se borra de S3 despues de guardar. Devuelve el id.
 */
export const guardarPromocion = async ({ idpromocion, datos, foto, idusuario }) => {
    const limpio = normalizarDatos(datos);
    const nueva = !idpromocion;
    const errores = validarPromocion(limpio, { nueva });
    if (Object.keys(errores).length) throw new ErrorPromocion(400, 'Revisa los datos de la promoción.', errores);
    if (nueva && !foto) throw new ErrorPromocion(400, 'Falta la foto de la temporada.', { foto: 'photoRequired' });
    const malos = limpio.productos.filter((p) => !TIPOS_DESCUENTO.includes(p.tipo) || !Number.isFinite(p.valor));
    if (malos.length) throw new ErrorPromocion(400, 'Hay descuentos no validos.', { productos: 'discountInvalid' });

    let fotoNueva = null;
    let fotoVieja = null;
    try {
        const id = await enTransaccion(async (tx) => {
            for (const sql of CREAR_TABLAS) await tx.escribir(sql);

            // Cada producto tiene que estar activo y en WEB, y su descuento
            // tiene que bajar el precio de WEB de hoy.
            const precios = await tx.consultar(
                `SELECT p.num_parte, max(d.precio) AS precio
                   FROM producto p
                   JOIN detalle d USING (num_parte)
                   JOIN sucursal s USING (idsucursal)
                  WHERE p.status = 'A' AND s.sucursal = 'WEB' AND p.num_parte = ANY(?::text[])
                  GROUP BY p.num_parte`,
                [limpio.productos.map((p) => p.num_parte)]
            );
            const precioDe = new Map(precios.map((fila) => [fila.num_parte, Number(fila.precio)]));
            const fuera = limpio.productos.filter((p) => !(precioDe.get(p.num_parte) > 0)).map((p) => p.num_parte);
            if (fuera.length) {
                throw new ErrorPromocion(400, `No estan en WEB: ${fuera.join(', ')}.`, { productos: 'notInWeb', partes: fuera });
            }
            const sinDescuento = limpio.productos
                .filter((p) => precioPromocion(precioDe.get(p.num_parte), p.tipo, p.valor) === null)
                .map((p) => p.num_parte);
            if (sinDescuento.length) {
                throw new ErrorPromocion(400, `El descuento no baja el precio de: ${sinDescuento.join(', ')}.`, { productos: 'discountInvalid', partes: sinDescuento });
            }

            let idActual = idpromocion;
            if (nueva) {
                const [fila] = await tx.consultar(
                    `INSERT INTO promocion (titulo, descripcion, inicio, fin, activa, creado_por, actualizado_por)
                     VALUES (?, ?, ?, ?, ?, ?, ?) RETURNING idpromocion`,
                    [limpio.titulo, limpio.descripcion || null, limpio.inicio, limpio.fin, limpio.activa, idusuario, idusuario]
                );
                idActual = fila.idpromocion;
            } else {
                const [anterior] = await tx.consultar('SELECT foto FROM promocion WHERE idpromocion = ? FOR UPDATE', [idpromocion]);
                if (!anterior) throw new ErrorPromocion(404, 'La promoción ya no existe.');
                fotoVieja = foto ? anterior.foto : null;
                await tx.escribir(
                    `UPDATE promocion
                        SET titulo = ?, descripcion = ?, inicio = ?, fin = ?, activa = ?, actualizado_por = ?, actualizado = now()
                      WHERE idpromocion = ?`,
                    [limpio.titulo, limpio.descripcion || null, limpio.inicio, limpio.fin, limpio.activa, idusuario, idpromocion]
                );
                await tx.escribir('DELETE FROM promocion_producto WHERE idpromocion = ?', [idpromocion]);
            }

            for (const producto of limpio.productos) {
                await tx.escribir(
                    'INSERT INTO promocion_producto (idpromocion, num_parte, tipo, valor) VALUES (?, ?, ?, ?)',
                    [idActual, producto.num_parte, producto.tipo, producto.valor]
                );
            }

            // La foto va al final: si algo de arriba falla, no se sube nada.
            if (foto) {
                fotoNueva = await subirFoto(idActual, foto);
                await tx.escribir('UPDATE promocion SET foto = ? WHERE idpromocion = ?', [fotoNueva, idActual]);
            }
            return idActual;
        });
        await borrarFoto(fotoVieja);
        return id;
    } catch (error) {
        // Si la foto subio y la transaccion no se guardo, no se queda huerfana.
        await borrarFoto(fotoNueva);
        throw error;
    }
};

/** Pausa o reanuda una promocion sin tocar lo demas. */
export const cambiarActiva = async ({ idpromocion, activa, idusuario }) => {
    const filas = await leerFilas(
        'UPDATE promocion SET activa = ?, actualizado_por = ?, actualizado = now() WHERE idpromocion = ? RETURNING idpromocion',
        [Boolean(activa), idusuario, idpromocion]
    );
    if (!filas.length) throw new ErrorPromocion(404, 'La promoción ya no existe.');
};

/** Borra la promocion (sus productos se van en cascada) y su foto. */
export const borrarPromocion = async (idpromocion) => {
    const filas = await leerFilas('DELETE FROM promocion WHERE idpromocion = ? RETURNING foto', [idpromocion]);
    if (!filas.length) throw new ErrorPromocion(404, 'La promoción ya no existe.');
    await borrarFoto(filas[0].foto);
};
